import { createServer } from 'node:http';
import { createReadStream } from 'node:fs';
import { stat } from 'node:fs/promises';
import assert from 'node:assert/strict';
import path from 'node:path';
const media = path.resolve('.test-data/browser/media');
await stat(path.join(media, 'source.mp4')); // generated by run.mjs, never user media
const server = createServer(async (req, res) => {
  const pathname = new URL(req.url, 'http://127.0.0.1').pathname;
  if (pathname === '/') { res.setHeader('Content-Type', 'text/html; charset=utf-8'); res.end('<!doctype html><meta charset="utf-8"><title>LMD manual permission fixture</title><h1>Собственный синтетический материал LMD</h1><p>Видео не запускается автоматически. Сначала проверьте отсутствие доступа в popup, затем откажите и повторите с разрешением.</p><video controls preload="none" src="/source.mp4"></video><p><a href="/vod.m3u8">HLS-манифест</a></p>'); return; }
  if (pathname === '/favicon.ico') { res.writeHead(204).end(); return; }
  if (!/^\/(?:source\.mp4|vod\.m3u8|seg-\d+\.ts)$/.test(pathname)) { res.writeHead(404).end(); return; }
  try {
    const file = path.join(media, pathname.slice(1)), info = await stat(file);
    res.writeHead(200, { 'Content-Type': pathname.endsWith('.mp4') ? 'video/mp4' : pathname.endsWith('.m3u8') ? 'application/vnd.apple.mpegurl' : 'video/mp2t', 'Content-Length': info.size, ETag: '"manual-v1"' });
    createReadStream(file).pipe(res);
  } catch { res.writeHead(404).end(); }
});
await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
const origin = `http://127.0.0.1:${server.address().port}`;
console.log(`Loopback-only synthetic fixture: ${origin}\nManual installation instructions: docs/evidence/t_8590b0cf/INSTALL.md\nCtrl+C closes only this server.`);
if (process.argv.includes('--smoke')) {
  try { assert((await (await fetch(origin)).text()).includes('LMD manual permission fixture')); const r = await fetch(`${origin}/source.mp4`); assert.equal(r.headers.get('content-type'), 'video/mp4'); assert((await r.arrayBuffer()).byteLength > 0); assert.equal((await fetch(`${origin}/../package.json`)).status, 404); console.log('Manual fixture smoke passed.'); }
  finally { await new Promise(resolve => server.close(resolve)); }
} else {
  const close = () => { server.close(); server.closeAllConnections(); };
  process.once('SIGINT', close); process.once('SIGTERM', close);
}
